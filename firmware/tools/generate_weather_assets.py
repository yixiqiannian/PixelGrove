"""Rasterize the pixel-weather asset pack into LVGL image descriptors.

Same approach as generate_pixel_farm_assets.py: everything becomes a static
const array referenced directly by LVGL, so there is zero decode and zero
runtime allocation.

- backgrounds (360x360, opaque)   -> RGB565   ~253 KiB each
- weather icons  (48x48, alpha)   -> ARGB8888  ~9 KiB each
- rain/snow (360x360, sparse)     -> A8 only   ~127 KiB each
  The effect frames are 1.8-3.6% opaque monochrome overlay. Storing them as
  ARGB8888 would need 4 MiB (more than the free flash); A8 keeps the alpha
  mask and the colour is applied at draw time with lv_image recolor
  (LVGL 9.4: lv_draw_image.h documents A8 + recolor as the intended usage).
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
ASSETS = Path(r"F:\CABadgeBuild\pixel_farm_weather_assets_v1\pixel_farm_weather_v1")
# 四季白天场景补充包：tree_free 背景（树已从背景里移除，方便日后单独叠加树木动画）
SEASONS = Path(r"F:\CABadgeBuild\pixel_weather_seasons_addon_v1\pixel_weather_seasons_addon_v1")
# 四季夜景补充包：夜色背景（窗灯/门灯已烘焙进图，月亮与星光为独立图层，本版未叠加）
NIGHTS = Path(r"F:\CABadgeBuild\pixel_weather_four_seasons_night_v1 (1)\pixel_weather_four_seasons_night_v1")
OUT = ROOT / "ui" / "weather_assets.c"


def load(rel, root=None):
    path = (root or ASSETS) / rel
    if not path.exists():
        sys.exit(f"missing asset: {path}")
    return Image.open(path)


def argb_dsc(name, im):
    raw = im.convert("RGBA").tobytes("raw", "BGRA")
    w, h = im.size
    body = ",".join(map(str, raw))
    return (
        f"static const uint8_t {name}_data[]={{{body}}};\n"
        f"const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,"
        f".cf=LV_COLOR_FORMAT_ARGB8888,.w={w},.h={h},.stride={w * 4}}},"
        f".data_size=sizeof({name}_data),.data={name}_data}};\n"
    )


def rgb565_dsc(name, im):
    im = im.convert("RGB")
    w, h = im.size
    px = im.load()
    vals = []
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            vals.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    lines = []
    for i in range(0, len(vals), 24):          # keeps the .c readable
        lines.append(",".join(str(v) for v in vals[i:i + 24]))
    body = ",\n".join(lines)
    return (
        f"static const uint16_t {name}_data[]={{{body}}};\n"
        f"const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,"
        f".cf=LV_COLOR_FORMAT_RGB565,.w={w},.h={h},.stride={w * 2}}},"
        f".data_size=sizeof({name}_data),.data=(const uint8_t*){name}_data}};\n"
    )


def a8_dsc(name, im):
    """Alpha-only descriptor; visible pixels take the recolor set by the caller."""
    alpha = im.convert("RGBA").getchannel("A")
    w, h = im.size
    body = ",".join(map(str, alpha.tobytes()))
    return (
        f"static const uint8_t {name}_data[]={{{body}}};\n"
        f"const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,"
        f".cf=LV_COLOR_FORMAT_A8,.w={w},.h={h},.stride={w}}},"
        f".data_size=sizeof({name}_data),.data={name}_data}};\n"
    )


def main():
    out = ['#include "weather.h"\n',
           "/* Generated by generate_weather_assets.py - do not edit by hand. */\n"]

    # 1. backgrounds, index order must match WX_BG_* in weather.h
    #    0-3 四季白天 | 4-7 四季夜晚 | 8 阴雨
    bgs = []
    for key, rel, root in (("spring", "backgrounds/spring_tree_free_360.png", SEASONS),
                           ("summer", "backgrounds/summer_tree_free_360.png", SEASONS),
                           ("autumn", "backgrounds/autumn_tree_free_360.png", SEASONS),
                           ("winter", "backgrounds/winter_tree_free_360.png", SEASONS),
                           ("night_spring", "backgrounds/spring_night_tree_free_360.png", NIGHTS),
                           ("night_summer", "backgrounds/summer_night_tree_free_360.png", NIGHTS),
                           ("night_autumn", "backgrounds/autumn_night_tree_free_360.png", NIGHTS),
                           ("night_winter", "backgrounds/winter_night_tree_free_360.png", NIGHTS)):
        out.append(rgb565_dsc(f"wx_bg_{key}", load(rel, root)))
        bgs.append(f"&wx_bg_{key}")
    out.append("const lv_image_dsc_t *const wx_bg[8]={" + ",".join(bgs) + "};\n")

    # 2. weather icons, index order must match WX_ICON_* in weather.h
    icons = []
    for name in ("sun", "partly_cloudy", "cloud", "rain_cloud", "snow_cloud", "moon"):
        out.append(argb_dsc(f"wx_icon_{name}", load(f"icons/48/{name}.png")))
        icons.append(f"&wx_icon_{name}")
    out.append("const lv_image_dsc_t *const wx_icons[6]={" + ",".join(icons) + "};\n")

    # 3. rain / snow overlay frames as alpha-only.
    #    每帧 127 KiB，为四季树木动画腾空间，从 4 帧减到 2 帧（随机粒子，视觉差异很小）。
    for grp in ("rain", "snow"):
        frames = []
        for i in range(2):
            name = f"wx_{grp}_{i}"
            out.append(a8_dsc(name, load(f"effects/{grp}/frame_{i:03d}.png")))
            frames.append(f"&{name}")
        out.append(f"const lv_image_dsc_t *const wx_{grp}[2]={{" + ",".join(frames) + "};\n")

    # 4. 四季树木动画：昼夜各 4 季 × 4 帧，64×96 ARGB8888（LVGL 9.4 软件渲染器不支持 ARGB8565）
    #    索引 [组][帧]：0-3 = 白天 春/夏/秋/冬，4-7 = 夜晚 春/夏/秋/冬
    tree_sets = []
    for root, tag in ((SEASONS, "day"), (NIGHTS, "night")):
        for season in ("spring", "summer", "autumn", "winter"):
            frames = []
            for i in range(4):
                name = f"wx_tree_{tag}_{season}_{i}"
                out.append(argb_dsc(name, load(f"trees/64x96/{season}/frame_{i:03d}.png", root)))
                frames.append(f"&{name}")
            out.append(f"const lv_image_dsc_t *const wx_tree_{tag}_{season}[4]={{"
                       + ",".join(frames) + "};\n")
            tree_sets.append(f"wx_tree_{tag}_{season}")
    out.append("const lv_image_dsc_t *const *const wx_trees[8]={\n    "
               + ",\n    ".join(tree_sets) + "\n};\n")

    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
