"""Rasterize the pixel-farm asset pack into LVGL image descriptors.

Same approach as generate_app_assets.py: no runtime PNG decoder, all sprites are
static const arrays referenced directly by LVGL (zero decode, zero allocation).

- background: RGB565 (opaque, half the bytes of ARGB8888)
- crops / icons / sparkle: ARGB8888 in BGRA byte order (alpha preserved)
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
ASSETS = Path(r"F:\CABadgeBuild\pixel_farm_weather_assets_v1\pixel_farm_weather_v1")
OUT = ROOT / "ui" / "pixel_farm_assets.c"


def bgra_bytes(im):
    return im.convert("RGBA").tobytes("raw", "BGRA")


def argb_dsc(name, im):
    raw = bgra_bytes(im)
    w, h = im.size
    body = ",".join(map(str, raw))
    return (
        f"static const uint8_t {name}_data[]={{{body}}};\n"
        f"const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,"
        f".cf=LV_COLOR_FORMAT_ARGB8888,.w={w},.h={h},.stride={w * 4}}},"
        f".data_size=sizeof({name}_data),.data={name}_data}};\n"
    )


def rgb565_dsc(name, im):
    im = im.convert("RGB")
    w, h = im.size
    px = im.load()
    vals = []
    for y in range(h):
        for x in range(w):
            r, g, b = px[x, y]
            vals.append(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    # 24 values per line keeps the generated file readable and compiles fast.
    lines = []
    for i in range(0, len(vals), 24):
        lines.append(",".join(str(v) for v in vals[i:i + 24]))
    body = ",\n".join(lines)
    return (
        f"static const uint16_t {name}_data[]={{{body}}};\n"
        f"const lv_image_dsc_t {name}={{.header={{.magic=LV_IMAGE_HEADER_MAGIC,"
        f".cf=LV_COLOR_FORMAT_RGB565,.w={w},.h={h},.stride={w * 2}}},"
        f".data_size=sizeof({name}_data),.data=(const uint8_t*){name}_data}};\n"
    )


def load(rel):
    path = ASSETS / rel
    if not path.exists():
        sys.exit(f"missing asset: {path}")
    return Image.open(path)


def main():
    out = ['#include "pixel_farm.h"\n',
           "/* Generated by generate_pixel_farm_assets.py - do not edit by hand. */\n"]

    out.append(rgb565_dsc("pf_bg", load("backgrounds/farm_day_360.png")))

    crops = []
    for crop in ("carrot", "turnip"):
        for stage in range(4):
            name = f"pf_{crop}_{stage}"
            out.append(argb_dsc(name, load(f"crops/48/{crop}_stage_{stage}.png")))
            crops.append(f"&{name}")
    out.append("const lv_image_dsc_t *const pf_crops[8]={"
               + ",".join(crops) + "};\n")

    icons = []
    for icon in ("seed_bag", "watering_can", "harvest_basket", "coin",
                 "soil_wet", "soil_dry"):
        name = f"pf_icon_{icon}"
        out.append(argb_dsc(name, load(f"icons/48/{icon}.png")))
        icons.append(f"&{name}")
    out.append("const lv_image_dsc_t *const pf_icons[6]={"
               + ",".join(icons) + "};\n")

    sparkle = []
    for frame in range(4):
        name = f"pf_sparkle_{frame}"
        out.append(argb_dsc(name, load(f"effects/harvest_sparkle/frame_{frame:03d}.png")))
        sparkle.append(f"&{name}")
    out.append("const lv_image_dsc_t *const pf_sparkle[4]={"
               + ",".join(sparkle) + "};\n")

    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size / 1024:.0f} KiB)")


if __name__ == "__main__":
    main()
